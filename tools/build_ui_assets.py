#!/usr/bin/env python3
"""Build the offline UI assets: the icon set (icons.js) and the bundled font (fonts.css).

Icons
  Every icon the app needs is collected from content/structure.json, the `icon:` field of each
  article and flow, and `icon("name")` calls plus `// icons:` comment lines in app.js, tools.js and map.js.
  SVGs come from third_party/lucide/icons (Lucide, ISC licence) and third_party/icons-custom.
  To use a new Lucide icon, add it to the vendored set first:
      python3 tools/build_ui_assets.py --lucide /path/to/lucide-static/icons
  which copies any missing icons from an extracted `lucide-static` npm package.
  Output: app/src/main/assets/icons.js, i.e. window.ICONS = {name: "<path …/>…"}; app.js turns
  these into an inline SVG sprite at start-up. (External <use> references and web fonts are blocked
  on file:// pages, so everything is inlined.)

Fonts
  Atkinson Hyperlegible (SIL OFL 1.1, Braille Institute), latin subset, embedded as data: URIs in
  app/src/main/assets/fonts.css.

Standard library only.
"""
from __future__ import annotations

import argparse
import base64
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "app" / "src" / "main" / "assets"
LUCIDE = ROOT / "third_party" / "lucide" / "icons"
CUSTOM = ROOT / "third_party" / "icons-custom"
FONTS = ROOT / "third_party" / "atkinson-hyperlegible"


def wanted_icons() -> set[str]:
    st = json.loads((ROOT / "content" / "structure.json").read_text(encoding="utf-8"))
    names = {u["icon"] for u in st["urgent"]}
    for g in st["groups"]:
        names.add(g["icon"])
        names |= {c["icon"] for c in g["categories"]} | {lk["icon"] for lk in g.get("links", [])}
    for p in list((ROOT / "content" / "articles").glob("*.md")) + list((ROOT / "content" / "flows").glob("*.md")):
        names |= set(re.findall(r"^icon:\s*([a-z0-9-]+)\s*$", p.read_text(encoding="utf-8"), re.M))
    js = "\n".join((ASSETS / f).read_text(encoding="utf-8") for f in ("app.js", "tools.js", "map.js") if (ASSETS / f).exists())
    names |= set(re.findall(r"""\bicon\(\s*["']([a-z0-9-]+)["']""", js))
    for line in re.findall(r"//\s*icons:(.*)", js):
        names |= set(line.split())
    return names


def svg_inner(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    inner = re.search(r"<svg[^>]*>(.*)</svg>", text, re.S).group(1)
    inner = re.sub(r"\s+", " ", inner).replace("> <", "><").strip()
    return inner


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lucide", help="path to lucide-static/icons to copy missing icons from")
    args = ap.parse_args()

    names = wanted_icons()
    icons: dict[str, str] = {}
    missing = []
    for n in sorted(names):
        custom = CUSTOM / f"{n}.svg"
        vend = LUCIDE / f"{n}.svg"
        if custom.exists():
            icons[n] = svg_inner(custom)
            continue
        if not vend.exists() and args.lucide and (Path(args.lucide) / f"{n}.svg").exists():
            LUCIDE.mkdir(parents=True, exist_ok=True)
            shutil.copy(Path(args.lucide) / f"{n}.svg", vend)
        if vend.exists():
            icons[n] = svg_inner(vend)
        else:
            missing.append(n)
    if missing:
        print("ERROR: icons not found (vendor them with --lucide):", ", ".join(missing), file=sys.stderr)
        return 1
    # Drop vendored icons nothing uses any more, so the repo only holds what ships.
    for p in LUCIDE.glob("*.svg"):
        if p.stem not in names:
            p.unlink()
    payload = json.dumps(icons, separators=(",", ":"), sort_keys=True)
    (ASSETS / "icons.js").write_text(
        "/* Icons: Lucide (ISC licence, lucide.dev) + custom icons in the same style. Generated by tools/build_ui_assets.py */\n"
        f"window.ICONS={payload};\n", encoding="utf-8")

    faces = [("400-normal", 400, "normal"), ("700-normal", 700, "normal"), ("400-italic", 400, "italic")]
    css = ["/* Atkinson Hyperlegible, (c) 2020 Braille Institute of America, SIL Open Font License 1.1.",
           "   Latin subset embedded as data URIs (file:// pages cannot load web fonts). Generated by tools/build_ui_assets.py */"]
    for suffix, weight, style in faces:
        data = (FONTS / f"atkinson-hyperlegible-latin-{suffix}.woff2").read_bytes()
        b64 = base64.b64encode(data).decode("ascii")
        css.append(f"@font-face{{font-family:'Atkinson Hyperlegible';font-style:{style};font-weight:{weight};"
                   f"font-display:block;src:url(data:font/woff2;base64,{b64}) format('woff2');}}")
    (ASSETS / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"{len(icons)} icons, {len(faces)} font faces")
    return 0


if __name__ == "__main__":
    sys.exit(main())
